static inline uint32_t fnv1a(uint32_t seed, uint32_t hash) {
    hash ^= seed & 0xFF; hash *= 0x01000193;
    hash ^= (seed >> 8) & 0xFF; hash *= 0x01000193;
    hash ^= (seed >> 16) & 0xFF; hash *= 0x01000193;
    hash ^= (seed >> 24) & 0xFF; hash *= 0x01000193;
    return hash;
}

static inline void build_shm_name(wchar_t* buf, size_t bufsz, uint32_t pid = 0) {
    const uint8_t k[] = {0xA1,0x37,0xE2,0x4C,0x8B,0x6D,0xF3,0x9A,0x21,0x55,0xCC,0x77,0x3E,0xD8,0x92,0x0F,0xBB,0x44,0xA6,0xE9,0x72,0x1D};
    const uint8_t e0[] = {0xED,0x58,0x81,0x2D,0xE7,0x31,0xB7,0xED,0x4C,0x06,0xA4,0x16,0x4C,0xBD,0xF6,0x42,0xDE,0x29,0xC9,0x9B,0x0B};
    wchar_t base[64];
    size_t i;
    for (i = 0; i < sizeof(base)/sizeof(base[0]) - 1 && i < sizeof(e0); i++) base[i] = (wchar_t)(e0[i] ^ k[i % sizeof(k)]);
    base[i] = L'\0';
    if (pid == 0) {
        for (i = 0; i < bufsz - 1 && base[i]; i++) buf[i] = base[i];
        buf[i] = L'\0';
    } else {
        uint32_t h = fnv1a(pid, 0x811C9DC5);
        wchar_t suffix[12];
        int slen = 0;
        suffix[slen++] = L'_';
        for (int d = 28; d >= 0; d -= 4) {
            int nyb = (h >> d) & 0xF;
            suffix[slen++] = (wchar_t)(nyb < 10 ? L'0' + nyb : L'A' + nyb - 10);
        }
        suffix[slen] = L'\0';
        size_t blen = 0;
        while (base[blen]) blen++;
        for (i = 0; i < bufsz - 1 && i < blen; i++) buf[i] = base[i];
        for (int j = 0; i < bufsz - 1 && j < slen; i++, j++) buf[i] = suffix[j];
        buf[i] = L'\0';
    }
    for (size_t z = 0; z < sizeof(base)/sizeof(base[0]); z++) base[z] = 0;
}

